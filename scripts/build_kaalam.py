def illai(sol):
    """நூல் முழுவதிலும் அச்சொல் தனிச்சொல்லாக இல்லை என்பதை உறுதி செய்தல்."""
    return not re.search(r"(^|[\s/])" + sol + r"($|[\s/])", ALL)


