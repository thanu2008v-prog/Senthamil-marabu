def eN(i):
    a, n = i.split(".")
    return f"{PAD[a]} {n}"


def uru(x):
    if isinstance(x, list):
        return "+".join(map(uru, x))
    if isinstance(x, dict):
        return f"{x.get('name')} [{x.get('test')}]" if x.get("test") else str(x.get("name"))
    return str(x)


def f(xs):
    return " ∧ ".join(f"«{x}»" for x in xs) if xs else ""


MODAL = {"கட்டாயம்": "□ ", "இசைவு": "◇ ", "விலக்கின்மை": "◇ ", "மறுப்பு": "¬ "}


def vaaipaadu(p):
    murai = p.get("murai") or []
    mod = "".join(MODAL[m] for m in murai if m in MODAL)
    pre = "புலவர் ⊢ " if "புலவர் கூற்று" in murai else ""
    e, n, v = f(p.get("ezhuvaai")), f(p.get("nibanthanai")), f(p.get("vilaivu"))
    vg = p["vagai"]
    if vg == "மாட்டேறு":
        mt = p.get("maatteru") or {}
        s = ", ".join(eN(x) for x in mt.get("suttu", [])) or "?"
        body = f"{e or 'இது'}{(' ∧ ' + n) if n else ''} : விதி ≔ விதி({s})"
    elif vg == "வரையறை":
        body = f"{e or '?'} ≝ {v or '?'}"
    elif vg == "எண்ணல்":
        u = p.get("uruppugal")
        body = f"|{e or v or '?'}| = {p['alavu'] if p.get('alavu') is not None else '?'}"
        if u:
            body += " = {" + ", ".join(map(uru, u)) + "}"
    elif vg == "பகுப்பு":
        u = p.get("uruppugal")
        parts = ", ".join(map(uru, u)) if u else (v or "?")
        body = f"{e or '?'} = ⊔ {{{parts}}}"
    elif vg == "நெறி":
        body = f"□ நெறி: {e or '?'} — {v or '?'}"
    else:                                                             # விதி, விலக்கு
        lhs = " ∧ ".join(x for x in (e, n) if x) or "?"
        body = f"∀x: {lhs} → {mod}{v or '?'}"
        mod = ""
    if vg != "விதி" and vg != "விலக்கு" and mod:
        body = mod + "(" + body + ")"
    return pre + body


