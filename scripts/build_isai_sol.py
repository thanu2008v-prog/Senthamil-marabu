found = []
for (pad, n), t in MOOL.items():
    for x in re.finditer(r"\S*(?:இசை|[க-ஹ]ிசை)\S*", t.replace("\n", " ")):
        found.append((pad, n, x.group()))
poli = [f for f in found if POLI_RE.search(f[2])]
real = [f for f in found if not POLI_RE.search(f[2])]
kai = Counter((P[a], n, w) for a, n, w, *_ in KAI)
got = Counter(real)
assert kai == got, ("கை வகைப்பாட்டில் விடுபட்டவை", sorted(got - kai), "மிகுந்தவை", sorted(kai - got))
for a, n, w, *_ in KAI:
    assert w in MOOL[(P[a], n)].replace("\n", " "), (a, n, w)

by = defaultdict(list)
for row in KAI:
    by[row[3]].append(row)
cnt = Counter(r[3] for r in KAI)
NURPA = sorted({(P[a], n) for a, n, *_ in KAI}, key=lambda x: (list(PAD).index(x[0]), x[1]))
