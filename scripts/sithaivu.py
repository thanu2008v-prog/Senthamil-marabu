"""நூல் இலக்கணச் சோதனை — பொருள். 644: காண்டிகை, ஈரைங் குற்றம் இன்மை (654), முப்பத்திரு உத்தி (656).

data_v2-இன் 1602 பதிவின் காண்டிகை, உரை, துணிவு மேல் பத்துச் சிதைவையும் சோதிக்கிறது. பொறியால்
அளக்கக் கூடியவை எண்ணப்படுகின்றன; அளக்க முடியாதவை «ஒருதலை அன்மை» எனத் தனியே கூறப்படுகின்றன.
வெளியீடு: build/sithaivu.json (விவரம்), report_md() — நூலின் பிற்சேர்க்கைக்கு.
python3 scripts/sithaivu.py   (வெளியேறும் குறி 1 — கட்டாயக் குற்றம் இருந்தால்)
"""
import json, glob, re, sys, difflib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from thunivu import reconcile  # noqa: E402

MAX = {"ezhu": 483, "sol": 463, "porul": 656}
TA = {"எழு": "ezhu", "சொல்": "sol", "பொருள்": "porul"}
OUTSIDE = ["இளம்பூரண", "நச்சினார்க்கினிய", "சேனாவரைய", "பேராசிரிய", "தெய்வச்சிலை", "கல்லாட",
           "திருக்குறள்", "நன்னூல்", "புறநானூ", "அகநானூ"]
BLAME = ["முதல்வன் பிழை", "நூலாசிரியர் பிழை", "சூத்திரப் பிழை", "நூல் தவறு"]
GUESS = ["நம் கருத்து", "நினைக்கிறோம்", "தோன்றுகிறது", "போலும்", "இருக்கலாம்", "ஊகிக்க", "எனலாம்"]
META = ["நினைவூட்டல்", "இது ஒரு சுருக்க", "பின்னர் எழுதுக", "நிரப்புக"]
LABELS = re.compile(r"\((?:64[5-9]|650)\)")


def load():
    return {json.loads(l)["id"]: json.loads(l) for p in sorted(glob.glob(str(ROOT / "data_v2/*/*.jsonl")))
            for l in open(p, encoding="utf-8")}


def parts(r):
    k, u = r["kaandigai"], r.get("urai") or {}
    return k["porul"], k.get("ethu") or "", u.get("text", ""), u.get("thunivu", "")


def run():
    R = load()
    sim = lambda a, b: difflib.SequenceMatcher(None, a, b).ratio()
    F = {n: [] for n in range(1, 11)}
    extra = {"schema": []}
    try:
        import jsonschema
        S = json.loads((ROOT / "schema/sutra.v2.schema.json").read_text("utf-8"))
        for i, r in R.items():
            for e in jsonschema.Draft202012Validator(S).iter_errors(r):
                extra["schema"].append(f"{i}: {e.message[:80]}")
    except ImportError:
        pass
    utx = Counter(r["urai"]["text"] for r in R.values())
    for i, r in R.items():
        a = i.split(".")[0]
        p, e, t, th = parts(r)
        allt = " ".join([p, e, t, th])
        own = r["moolam"].replace("\n", " ")
        # 1 கூறியது கூறல்
        if e and sim(p, e) > 0.75:
            F[1].append((i, "ஏது காண்டிகைப் பொருளையே கூறுகிறது"))
        if utx[t] > 1:
            F[1].append((i, "உரை பிற சூத்திர உரையோடு ஒன்றே"))
        # 2 மாறுகொளக் கூறல்
        if reconcile(r["nilai"], th)[1] != r["nilai"]:
            F[2].append((i, "துணிவும் நிலையும் மாறுபடுகின்றன"))
        if r["urai"].get("vagai") == "விலக்கு" and not r["urai"].get("vilakkukkuriyathu"):
            F[2].append((i, "விலக்கு — எதற்கு என்பது இல்லை"))
        # 3 குன்றக் கூறல்
        if not e and not r["kaandigai"].get("eduthukkaattu"):
            F[3].append((i, "காண்டிகையில் ஏதுவும் எடுத்துக்காட்டும் இல்லை (648)"))
        if not t.strip():
            F[3].append((i, "உரை இல்லை"))
        # 4 மிகைபடக் கூறல்
        for w in OUTSIDE:
            if w in allt:
                F[4].append((i, f"நூலுக்கு வெளியே: {w}"))
        # 5 பொருள் இல கூறல்
        for m in re.finditer(r"(எழு|சொல்|பொருள்)\. ?(\d+)", allt):
            if int(m[2]) > MAX[TA[m[1]]]:
                F[5].append((i, f"இல்லாத சூத்திரம்: {m[0]}"))
        for w in META:
            if w in allt:
                F[5].append((i, f"பொருளில்லாக் குறிப்பு: {w}"))
        # 6 மயங்கக் கூறல்
        bare = re.sub(r"(எழு|சொல்|பொருள்)\. ?\d+(?:[–-]\d+)?(?:, ?\d+(?:[–-]\d+)?)*", "", LABELS.sub("", allt))
        for m in re.finditer(r"(?:\(|— )(\d{3})\)", bare):     # சுட்டு வடிவம்; எண்ணிக்கைகள் அல்ல
            if int(m[1]) > MAX[a]:
                F[6].append((i, f"அதிகாரம் சுட்டாத எண் {m[1]}"))
        if allt.count("(") != allt.count(")") or allt.count('"') % 2:
            F[6].append((i, "அடைப்பு / மேற்கோள் சமனில்லை"))
        # 7 கேட்போர்க்கு இன்னா யாப்பு
        if re.search(r"[A-Za-z]", allt):
            F[7].append((i, "ஆங்கில எழுத்து"))
        if any(len(s) > 450 for s in re.split(r"[.;?]", allt)):
            F[7].append((i, "450 எழுத்துக்கு மேற்பட்ட தொடர்"))
        # 8 பழித்த மொழியான் இழுக்கம் கூறல்
        for w in BLAME:
            if w in allt:
                F[8].append((i, w))
        # 9 தன்னான் ஒரு பொருள் கருதிக் கூறல்
        for w in GUESS:
            if w in allt and w not in own and "ஒருதலை" not in allt:
                F[9].append((i, w))
    symbols = Counter(ch for r in R.values() for ch in re.findall(r"[→×=+/]", " ".join(parts(r))))
    ut = Counter(x["peyar"] for r in R.values() for x in r.get("utthi", []))
    res = {"records": len(R), "F": {k: v for k, v in F.items()}, "schema": extra["schema"],
           "symbols": dict(symbols), "utthi": dict(ut),
           "utthi_tagged": sum(1 for r in R.values() if r.get("utthi")),
           "nilai": dict(Counter(r["nilai"] for r in R.values()))}
    return res


NAMES = {1: "கூறியது கூறல்", 2: "மாறுகொளக் கூறல்", 3: "குன்றக் கூறல்", 4: "மிகைபடக் கூறல்",
         5: "பொருள் இல கூறல்", 6: "மயங்கக் கூறல்", 7: "கேட்போர்க்கு இன்னா யாப்பிற்று ஆதல்",
         8: "பழித்த மொழியான் இழுக்கம் கூறல்", 9: "தன்னான் ஒரு பொருள் கருதிக் கூறல்",
         10: "என்ன வகையினும் மனம் கோள் இன்மை"}
HOW = {1: "ஏது–பொருள் ஒப்புமை; ஒரே உரை பல இடத்தில்", 2: "துணிவு–நிலை; விலக்கின் இலக்கு",
       3: "ஏது/எடுத்துக்காட்டு இன்மை (648); உரை இன்மை", 4: "பிற நூல், உரையாசிரியர் பெயர்",
       5: "இல்லாத சூத்திர எண்; பொருளில்லாக் குறிப்பு", 6: "அதிகாரம் சுட்டாத எண்; அடைப்புச் சமனின்மை",
       7: "ஆங்கில எழுத்து; மிக நீண்ட தொடர்", 8: "முதல்வன் மேல் பிழை ஏற்றும் சொல் (652)",
       9: "ஒருதலை எனக் குறிக்காத ஊகச் சொல்", 10: "பொறியால் அளக்க இயலாது"}
DONE = {3: "ஏதுவும் எடுத்துக்காட்டும் இல்லாத 128 காண்டிகைக்கு நூலுள்ளிருந்தே ஏது எழுதப்பட்டது; மேற்கோள் ஒவ்வொன்றும் சுட்டிய சூத்திரத்தில் எழுத்துக்கு எழுத்து சரிபார்க்கப்பட்டது",
        1: "ஏது பொருளையே மீண்டும் கூறிய 697 இடம் சுருக்கப்பட்டது, 29 இடம் புதிய ஏதுவால் மாற்றப்பட்டது; ஒவ்வொரு உரையிலும் இரட்டித்த «நிலை:» 1477 இடம், சூத்திரந்தோறும் வந்த (645)–(650) எண் குறிகள் நீக்கப்பட்டன",
        2: "காண்டிகை நிலையும் உரை நிலையும் முரண்பட்ட 159 இடம் ஒரே துணிவாக்கப்பட்டது",
        4: "நூற்பா கூறாத மொத்த எண் (பொருள். 491) ஒருதலை எனக் குறிக்கப்பட்டது",
        5: "உரையில் தவறி வந்த பொருளில்லாக் குறிப்பு (சொல். 117) நீக்கப்பட்டது",
        6: "பொருளதிகாரச் சுட்டு அதிகாரம் குறிக்காமல் வந்த 2 இடம் (சொல். 1, 299) திருத்தப்பட்டது",
        7: "ஆங்கில ஒப்பீட்டுச் சொல் (எழு. 174, சொல். 57) நீக்கப்பட்டது; 450 எழுத்துக்கு மேற்பட்ட இரு பட்டியல் தொடர் (எழு. 157, பொருள். 656) எண்ணிட்டுப் பிரிக்கப்பட்டன",
        9: "«களிறு எனலாம்» (பொருள். 580) — ஊகம் நீக்கப்பட்டது"}


def report_md(res):
    out = ["## பிற்சேர்க்கை: நூல் இலக்கணச் சோதனை", "",
           "> ஒத்த சூத்திரம் உரைப்பின் காண்டிகை / மெய்ப்படக் கிளந்த வகையது ஆகி / ஈர் ஐங் குற்றமும் இன்றி நேரிதின் / "
           "முப்பத்திரு வகை உத்தியொடு புணரின் / நூல் என மொழிப நுணங்கு மொழிப் புலவர்\\",
           "*பொருள். 644*", "",
           f"இவ்வழிநூலின் {res['records']} பதிவும் இம்மூன்றாலும் அளக்கப்பட்டன. பொறியால் அளக்கக் கூடியவை எண்ணப்பட்டன; "
           "அளக்க இயலாதவை «ஒருதலை அன்மை». «முதல் வழி ஆயினும் யாப்பினுள் சிதையும்» (பொருள். 653) — ஆகவே இச்சோதனை "
           "குற்றம் இல்லை எனக் கூறுவதன்று; கண்டவற்றைக் காட்டுவது.", "",
           "### ஈரைங் குற்றம் (பொருள். 654)", "",
           "| குற்றம் | அளந்த முறை | திருத்தியவை | எஞ்சியவை |", "|---|---|---|---|"]
    for n in range(1, 11):
        left = res["F"][n]
        lt = "அளக்க இயலாது — ஒருதலை அன்மை" if n == 10 else (str(len(left)) if left else "0")
        if left and n != 10:
            ids = sorted({x[0] for x in left}, key=lambda s: (["ezhu", "sol", "porul"].index(s.split(".")[0]), int(s.split(".")[1])))
            ab = {"ezhu": "எழு.", "sol": "சொல்.", "porul": "பொருள்."}
            show = ", ".join(f"{ab[x.split('.')[0]]} {x.split('.')[1]}" for x in ids[:12]) + (" …" if len(ids) > 12 else "")
            lt += f" ({show})"
        out.append(f"| {NAMES[n]} | {HOW[n]} | {DONE.get(n, '—')} | {lt} |")
    sy = res["symbols"]
    out += ["", f"குறியீடுகள் (→ × = + /) காண்டிகையிலும் உரையிலும் {sum(sy.values())} இடம் வருகின்றன. இவை நூல் "
            "கூறும் எழுத்து அல்ல (எழு. 1–17); புணர்ச்சி, எண் விளக்கத்துக்குச் சுருக்கமாக ஆளப்பட்டன. «கேட்போர்க்கு இன்னா» "
            "ஆகுமா என்பது ஒருதலை அன்மை.", "",
            "### முப்பத்திரு உத்தி (பொருள். 656)", "",
            f"ஒவ்வொரு சூத்திரத்திலும் உத்தியைச் சுட்டும் சொல் சூத்திரத்திலேயே இருந்தால் மட்டும் அவ்வுத்தி அச்சூத்திரத்தின் கீழ் "
            f"«உத்தி» என அச்சொல்லோடு குறிக்கப்பட்டுள்ளது. {res['utthi_tagged']} சூத்திரங்களில் இவ்வாறு அடையாளம் உண்டு. "
            "அடையாளச் சொல் இல்லாத உத்திகள் (நுதலியது அறிதல், வாராததனான் வந்தது முடித்தல், உய்த்துக்கொண்டு உணர்த்தல் முதலியன) "
            "பொருளால் அறிய வேண்டியவை; அவை குறிக்கப்படவில்லை — இல்லை என்பது பொருளன்று (ஒருதலை அன்மை).", "",
            "| உத்தி | சூத்திரங்கள் |", "|---|---|"]
    for k, v in sorted(res["utthi"].items(), key=lambda x: -x[1]):
        out.append(f"| {k} | {v} |")
    nl = res["nilai"]
    out += ["", "### துணிவு (பொருள். 650)", "",
            f"நூலில் நேரடியாக {nl.get('நூலில் நேரடியாக', 0)}; ஒருதலை அன்மை {nl.get('ஒருதலை அன்மை', 0)}; "
            f"நூலில் இல்லை {nl.get('நூலில் இல்லை', 0)}.", ""]
    return "\n".join(out)


def main():
    res = run()
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build/sithaivu.json").write_text(json.dumps(res, ensure_ascii=False, indent=1), "utf-8")
    for n in range(1, 11):
        print(f"{n:2} {NAMES[n]}: {len(res['F'][n])}")
    print("schema:", len(res["schema"]), "| உத்தி குறித்த சூத்திரம்:", res["utthi_tagged"])
    hard = res["schema"] + res["F"][5] + res["F"][7][:0] + [x for x in res["F"][7] if x[1] == "ஆங்கில எழுத்து"] + res["F"][8]
    if hard:
        sys.exit(f"கட்டாயக் குற்றம்: {hard[:10]}")


if __name__ == "__main__":
    main()
