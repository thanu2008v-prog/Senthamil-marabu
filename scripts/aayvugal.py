def build():
    md = SRC.read_text("utf-8")
    head, *parts = re.split(r"(?m)^(?=### )", md)
    intro = head.split("\n", 1)[1].strip()
    out, old2new, n = [], {}, 0
    for i, p in enumerate(parts):
        if i in DROP:
            continue
        lines = [ln for ln in p.rstrip().split("\n") if not LINE_DROP.match(ln)]
        p = "\n".join(lines)
        for a, b in SUBS:
            p = re.sub(a, b, p)
        m = re.match(r"### (\d+)\. ", p)
        if m:
            n += 1
            old2new.setdefault(int(m[1]), n)       # இருமுறை வந்த எண் — முதலாவது (உடல் சுட்டுவது அதையே)
            p = f"### {n}. " + p[m.end():]
        else:
            p = "#" + p                              # எண்ணில்லாத உட்பிரிவு ("பிறப்பு")
        out.append(p)
    return intro, out, old2new


def remap(text, old2new):
    def one(m):
        nums = [old2new.get(int(x), int(x)) for x in re.split(r", ?", m[1])]
        return "ஆய்வு " + ", ".join(map(str, nums))
    return re.sub(r"ஆய்வு (\d+(?:, ?\d+)*)", one, text)


def appendix():
    intro, parts, old2new = build()
    body = "\n\n".join(remap(p, old2new) for p in parts)
    md = f"## பிற்சேர்க்கை: ஆய்வுகள்\n\n{intro}\n\n{body}\n"
    left = sorted(set(re.findall(r"[A-Za-z][A-Za-z0-9_.\-]*", md)) - {"Project", "Madurai", "Claude"})
    return md, old2new, left


