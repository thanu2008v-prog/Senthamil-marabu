"""தமிழ் உரை: NFC, தேடல், வரிசை — நூல் கூறும் எழுத்து வரிசையின்படி.

வரிசை (sort_key):
  * உயிர் பன்னிரண்டு முதலில், அகரம் முதல் — "அகரமுதல்" (எழு. 1); உயிர் வரிசை எழு. 3, 4, 8.
  * மெய் — இறுதி னகரம்: "னகர இறுவாய்" (எழு. 1)                         → நூலில் நேரடியாக.
  * மெய்யின் இடை வரிசை: வல்லினம் "க ச ட த ப ற" (எழு. 19), மெல்லினம் "ங ஞ ண ந ம ன"
    (எழு. 20) இணையிடத்தில்; பிறப்பிலும் இணை — "ககார ஙகாரம்" (89), "சகார ஞகாரம்" (90),
    "டகார ணகாரம்" (91). இடையினம் "ய ர ல வ ழ ள" (எழு. 21) ற ன-க்கு முன் வருவதற்கு
    நூற்பா இல்லை                                                          → ஒருதலை அன்மை.
  * ஆய்தம் (ஃ) முப்பதில் சேராத சார்பெழுத்து — "மூன்றலங் கடையே" (எழு. 1),
    "முப்பாற் புள்ளியும் எழுத்தோ ரன்ன" (எழு. 2) — ஆகவே முப்பதுக்குப் பின்.
புணர்ச்சிப் பிரிப்பு இங்கு இல்லை: அது எழு. 103–483 விதி நிரலால் மட்டுமே செய்யப்படும்.
"""
import unicodedata
import re

UYIR = "அஆஇஈஉஊஎஏஐஒஓஔ"
MEY = "கஙசஞடணதநபமயரலவழளறன"       # இணை வரிசை — ஒருதலை அன்மை; ன இறுதி — எழு. 1
SAARPU = "ஃ"                         # எழு. 1, 2
TAMIL_ORDER = UYIR + MEY + SAARPU
ORDER = {c: i for i, c in enumerate(TAMIL_ORDER)}
SIGNS = "ாிீுூெேைொோௌ"                 # உயிர்க் குறிகள், உயிர் வரிசையில் (ஆ … ஔ)


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s).strip()


def sort_key(s: str):
    """எழுத்து வாரியான வரிசைச் சாவி: உயிர்மெய் = (மெய், உயிர்)."""
    s, key, i = nfc(s), [], 0
    while i < len(s):
        ch = s[i]
        nxt = s[i + 1] if i + 1 < len(s) else ""
        if ch in MEY:
            if nxt == "்":
                key += [ORDER[ch], -1]; i += 2           # மெய் (புள்ளி) — உயிர்மெய்க்கு முன்
            elif nxt and nxt in SIGNS:
                key += [ORDER[ch], SIGNS.index(nxt) + 1]; i += 2
            else:
                key += [ORDER[ch], 0]; i += 1            # அகரம்
        else:
            key += [ORDER.get(ch, 999), 0]; i += 1
    return key


def norm_search(s: str) -> str:
    """இடைவெளி நீக்கல் — 'அகரமுதல்', 'அகரம் முதல்' இரண்டும் கிடைக்க."""
    return re.sub(r"\s+", "", nfc(s))


if __name__ == "__main__":
    print(sorted(["னகரம்", "ஃ", "அகரம்", "கா", "க்", "க", "ஔ"], key=sort_key))
