// உரை → எழுத்துகள். ஒவ்வொன்றும் {k: உயிர்|மெய்|உயிர்மெய்|ஆய்தம்|பிற, c: மெய், v: உயிர், vada, s: உரை, at: இடம்}
function letters(text) {
  text = text.normalize("NFC");
  const out = [];
  for (let i = 0; i < text.length; ) {
    const ch = text[i];
    if (MEY.includes(ch) || VADA.includes(ch)) {
      const nx = text[i + 1] || "";
      const vada = VADA.includes(ch);
      if (nx === PULLI) { out.push({ k: "மெய்", c: ch, v: "", vada, s: ch + nx, at: i }); i += 2; }
      else if (SIGN[nx]) { out.push({ k: "உயிர்மெய்", c: ch, v: SIGN[nx], vada, s: ch + nx, at: i }); i += 2; }
      else { out.push({ k: "உயிர்மெய்", c: ch, v: "அ", vada, s: ch, at: i }); i += 1; }
    } else if (UYIR.includes(ch)) { out.push({ k: "உயிர்", c: "", v: ch, s: ch, at: i }); i += 1; }
    else if (ch === "ஃ") { out.push({ k: "ஆய்தம்", c: "", v: "", s: ch, at: i }); i += 1; }
    else { out.push({ k: "பிற", s: ch, at: i }); i += 1; }
  }
  return out;
}

// சொற்கள் — தமிழ் எழுத்துத் தொடர்கள்
function words(text) {
  const L = letters(text), W = [];
  let cur = [];
  for (const l of L) {
    if (l.k === "பிற") { if (cur.length) W.push(cur); cur = []; } else cur.push(l);
  }
  if (cur.length) W.push(cur);
  return W.map(ls => ({ ls, s: ls.map(l => l.s).join(""), start: ls[0].at, end: ls[ls.length - 1].at + ls[ls.length - 1].s.length }));
}

