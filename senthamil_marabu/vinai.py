def _strip(w):
    """«இலவே» → «இல», «உரித்தே» → «உரித்து», «உரியவே» → «உரிய» — ஈற்று அசை ஏகாரம் நீக்கல்."""
    o = to_oli(w)
    if o.endswith("ஏ") and len(o) > 3:
        body = o[:-1]
        if len(body) >= 3 and body[-2:] in ("வ்", "ய்") and body[-3] in "அஆஇஈஉஊஎஏஐஒஓஔ":
            body = body[:-2]               # இல + (வ்) + ஏ → «இலவே» — உடம்படுமெய் நீக்கல் (எழு. 140)
        elif body.endswith("்") and body[-2] in "கசடதபற":
            body += "உ"                    # உரித்தே → உரித்து (குற்றியலுகரம் கெட்டு ஏ ஏறியது)
        return body, True
    return o, False


def eeru(sol):
    """வினைமுற்று → பொருந்தும் ஈறுகள் (நீண்டது முன்). ஒவ்வொன்றும் {eeru, thinai, paal, idam, en, sutra, kurippu}."""
    if sol in THANI:
        rows = THANI[sol]
    else:
        o, asai = _strip(sol)
        rows = [e for oe, e in sorted(_ALL, key=lambda x: -len(x[0])) if o.endswith(oe) and len(o) > len(oe)]
    return [dict(eeru=e[0], thinai=e[1], paal=e[2], idam=e[3], en=e[4], sutra=e[5], kurippu=e[6]) for e in rows]
