"""உருபு புணர்ச்சி — பெயர் + (சாரியை) + வேற்றுமை உருபு (எழு. 113–135, 173–202; சொல். 63–84).

    from senthamil_marabu.urupu import urupu
    urupu("அது", "கு")        # அதற்கு — எழு. 176 (அன், உகரம் கெடும்), எழு. 332 (னகரம் றகரம்)
    urupu("மரம்", "ஐ")       # மரத்தை — எழு. 185 (அத்து), 133 (ஒற்றுமெய் கெடும்), 125
    urupu("அவை", "உள்")      # அவற்றுள் — எழு. 177, 122 (வற்று)

நெறி: சாரியைத் தேர்வும் சொல்லுக்கெனக் கூறிய திரிபும் நூற்பாவால் மட்டுமே; இணைப்பு புணர்ச்சிப் பொறியால் (வேற்றுமைப் புணர்ச்சி —
எழு. 116 «வேற்றுமை வழிய பெயர்புணர் நிலையே»). நூல் கூறாத இடத்தில் «ஒருதலை அன்மை».
"""
from itertools import product

from .punarchi import punar, to_oli, VAL

URUPU = {"ஐ": 2, "ஒடு": 3, "கு": 4, "இன்": 5, "அது": 6, "கண்": 7}           # எழு. 113; சொல். 65
EZHAAM_SOL = ["கண்", "கால்", "புறம்", "அகம்", "உள்", "உழை", "கீழ்", "மேல்", "பின்", "சார்", "அயல்", "புடை", "தேவகை",
              "முன்", "இடை", "கடை", "தலை", "வலம்", "இடம்"]                    # சொல். 83
N, O = "நூலில் நேரடியாக", "ஒருதலை அன்மை"
KURIL = set("அஇஉஎஒ")


def _p(sutra, vilakkam, nilai=N):
    return dict(sutra=sutra, vilakkam=vilakkam, nilai=nilai)


def _kutriyalukaram(w):
    o = to_oli(w)
    if not (len(o) >= 3 and o.endswith("உ") and o[-3] in VAL and o[-2] == "்"):
        return False
    body = o[:-3]                                    # உகரம் ஏறிய மெய்க்கு முன் உள்ளது
    short2 = (body in KURIL) or (len(body) == 3 and body[1] == "்" and body[2] in KURIL)
    return not short2                                # எழு. 406; 267 — குறிலை அடுத்த ஈரெழுத்துச் சொல் அன்று


def _ezhaam(u):
    return u in EZHAAM_SOL and u != "கண்"


# ── சொல்லுக்கெனக் கூறிய திரிபு: (நிலைமொழி) → [(அடி, சாரியை, படிகள்)]
def _thani(w, u, thinai):
    if w == "நீ":
        return [("நின்", None, [_p("எழு. 179", "நீ — நெடுமுதல் குறுகி னகரம் ஒற்றாகும்: நின்")])]
    if w in ("தாம்", "நாம்"):
        return [(w[0] + w[2:], None, [_p("எழு. 188", "நெடுமுதல் குறுகும்: " + w[0] + w[2:])])]
    if w == "யாம்":
        return [("எம்", None, [_p("எழு. 188", "யாம் — ஆ எ ஆகும்; யகரமெய் கெடும்: எம்")])]
    if w in ("தான்", "யான்"):
        st = "தன்" if w == "தான்" else "என்"
        return [(st, None, [_p("எழு. 192", "தாம், யாம் போல் வேறுபாடில்லை: " + st)])]
    if w == "நும்":
        return [("நும்", None, [_p("எழு. 187", "நும் — இயற்கையாகும்; சாரியை இல்லை")])]
    if w in ("அது", "இது", "உது"):
        return [(w[0] + "தன்", None, [_p("எழு. 176", "சுட்டுமுதல் உகரம் அன்னொடு சிவணி, ஒட்டிய மெய் ஒழிய உகரம் கெடும்: " + w[0] + "தன்")])]
    if w in ("அஃது", "இஃது", "உஃது", "யாது"):
        st = (w[0] + "தன்") if w != "யாது" else "யாதன்"
        return [(st, None, [_p("எழு. 200", "அன்னொடு சிவணும்; ஆய்தம் கெடும்: " + st)])]
    if w in ("அவை", "இவை", "உவை"):
        st = w[0] + "வற்று"
        return [(st, None, [_p("எழு. 177", "சுட்டுமுதல் ஐ ஈறு வற்றொடு சிவணும் (உரித்தே)"),
                            _p("எழு. 122", "வற்றின் வகரமெய் கெட, ஐயின் முன் அகரம் நிற்கும்: " + st)])]
    if w in ("யா", "யாவை"):
        return [("யாவற்று", None, [_p("எழு. 175" if w == "யா" else "எழு. 178", "யா வினா — வற்றொடு (174 இன் இயல் திரியாது)"
                                      + ("" if w == "யா" else "; வகரம் ஐயொடும் கெடும்"))])]
    if w == "எல்லாம்":
        if thinai == "உயர்திணை":
            return [("எல்லா|நம்", "உம்", [_p("எழு. 190", "உயர்திணையாயின் நம் இடை வரும்"), _p("எழு. 189", "உம் இறுதியில் நிற்கும்")])]
        return [("எல்லாவற்று", "உம்", [_p("எழு. 189", "வற்று முற்றத் தோன்றும்; மகரம் கெடும் (133); உம் இறுதியில் நிற்கும்")])]
    if w in ("எல்லாரும்", "எல்லீரும்"):
        st = "எல்லார்|தம்" if w == "எல்லாரும்" else "எல்லீர்|நும்"
        return [(st, "உம்", [_p("எழு. 191", "ஒற்றும் உகரமும் கெட ரகரப் புள்ளி நிற்கும்; "
                                + ("படர்க்கைக்குத் தம்" if w == "எல்லாரும்" else "முன்னிலைக்கு நும்") + " இடை வரும்; உம் இறுதியில்")])]
    if w in ("அழன்", "புழன்"):
        return [(w[:-2] + "த்து", None, [_p("எழு. 193", "அத்தும் இன்னும் உறழத் தோன்றும் — அத்து; ஒற்று கெடும் (133)")]),
                (w + "இன்", None, [_p("எழு. 193", "அத்தும் இன்னும் உறழத் தோன்றும் — இன்")])]
    return None


KURUMUTHAL = {"நின்", "தம்", "நம்", "எம்", "தன்", "என்", "நும்"}       # நெடுமுதல் குறுகும் மொழி (எழு. 161) + நும் (162)
ENN = {"ஒன்று", "இரண்டு", "மூன்று", "நான்கு", "ஐந்து", "ஆறு", "ஏழ்", "எட்டு", "ஒன்பது", "பத்து"}


def saariyai(w, u="ஐ", inam=None, thinai=None, palavai=False):
    """நிலைமொழிக்கும் உருபுக்கும் இடையே வரும் சாரியை → [(அடி வடிவு, உம் இறுதியா, படிகள்)]."""
    th = _thani(w, u, thinai)
    if th:
        return th
    o = to_oli(w)
    last = o[-1] if not o.endswith("்") else o[-2:]
    out = []
    if w in ENN:
        for r in punar(w, "அன்", "வேற்றுமை", thani_vithi=False):
            out.append((r["sol"], None, [_p("எழு. 198", "எண்ணின் இறுதி அன்னொடு சிவணும்: " + r["sol"])]))
        if w != "பத்து":
            for r in punar(w, "ஆன்", "வேற்றுமை", thani_vithi=False):
                out.append((r["sol"], None, [_p("எழு. 199", "ஆன் இடை வரினும் மானமில்லை: " + r["sol"])]))
        return out
    if u == "இன்":
        base = [(w, None, [_p("எழு. 131", "இன் உருபுக்கு இன் சாரியை இல்லை")])]
        if last == "ம்":                             # அத்து இன்னின் வேறு — 185 நிற்கும்
            st = w[:-2] + "த்து"
            return [(st, None, [_p("எழு. 185", "மகரப் புள்ளி முன் அத்து"), _p("எழு. 133", "அத்தின் மேல் ஒற்றுமெய் கெடும்"),
                                _p("எழு. 125", "அத்தின் அகரம் அகர முன் இல்லை")])] + base
        return base
    if last == "ஓ":
        return [(w + "ஒன்", None, [_p("எழு. 180", "ஓகார இறுதிக்கு ஒன் சாரியை")])]
    if palavai and last == "அ":
        return [(w + "வற்று", None, [_p("எழு. 174", "பல்லவை நுதலிய அகர இறு பெயர் வற்றொடு சிவணும்")])]
    if last in ("அ", "ஆ", "உ", "ஊ", "ஏ", "ஔ") and not _kutriyalukaram(w):
        out.append((w + "+இன்", None, [_p("எழு. 173", "அ ஆ உ ஊ ஏ ஔ இறுதி முன் உருபுக்கு இன் சாரியை")]))
        if last == "ஆ":
            out.append((w + "ன்", None, [_p("எழு. 173", "இன் சாரியை"), _p("எழு. 120", "இன்னின் இகரம் ஆவின் இறுதி முன் கெடுதல் உரித்து")]))
        if inam == "மரப்பெயர்" and last in ("அ", "ஆ") and (u == "கண்" or _ezhaam(u)):
            out.append((w + "த்து", None, [_p("எழு. 181", "அ ஆ மரப்பெயர்க்கு ஏழன் உருபு அத்தொடும் சிவணும்"),
                                           _p("எழு. 125", "அத்தின் அகரம் அகர முன் இல்லை")]))
        return out
    if last in ("ஞ்", "ந்"):
        return [(w + "+இன்", None, [_p("எழு. 182", "ஞ, ந புள்ளிக்கு இன் சாரியை")])]
    if last == "வ்":
        if inam == "சுட்டு":
            return [(w, None, [_p("எழு. 183", "சுட்டுமுதல் வகர இறுதி இயல்பு திரியாது")])]
        return [(w + "+இன்", None, [_p("எழு. 184", "ஏனை வகரம் இன்னொடு சிவணும்")])]
    if last == "ம்":
        return [(w[:-2] + "த்து", None, [_p("எழு. 185", "மகரப் புள்ளி முன் அத்து சாரியை"), _p("எழு. 133", "அத்தின் மேல் ஒற்றுமெய் கெடும்"),
                                         _p("எழு. 125", "அத்தின் அகரம் அகர முன் இல்லை")]),
                (w + "+இன்", None, [_p("எழு. 186", "இன் இடை வரும் மொழியும் உள", O)])]
    if _kutriyalukaram(w):
        return [(w + "+இன்", None, [_p("எழு. 195", "குற்றியலுகர இறுதி முன் இன் சாரியை முற்றத் தோன்றும்")])]
    return [(w, None, [_p("எழு. 202", "மற்றைப் புள்ளியீறும் உயிரீறும் — சாரியை நிற்கும் கடப்பாடு இல்லை")])]


def _join(a, b):
    """வேற்றுமைப் புணர்ச்சி → [(வடிவு, படிகள், நிலை)]."""
    out = []
    for r in punar(a, b, "வேற்றுமை", thani_vithi=False):
        out.append((r["sol"], [_p(", ".join(t["sutra"][0] for t in r["vithi"]), "புணர்ச்சி: " + "; ".join(t["vilakkam"] for t in r["vithi"]),
                                  r["nilai"])], r["nilai"]))
    return out


def urupu(peyar, u, inam=None, thinai=None, palavai=False):
    """பெயர் + வேற்றுமை உருபு → [{sol, vithi, nilai}]. u: ஐ, ஒடு, கு, இன், அது, கண் அல்லது சொல். 83 இன் ஏழன் உருபுச் சொல்."""
    if u not in URUPU and u not in EZHAAM_SOL:
        raise ValueError("உருபு: " + ", ".join(URUPU) + " அல்லது " + ", ".join(EZHAAM_SOL))
    res = []
    choices = saariyai(peyar, u, inam, thinai, palavai)
    if u == "ஒடு" and not any(c[0] == peyar for c in choices):
        choices = choices + [(peyar, None, [_p("எழு. 132", "சாரியை உடைமையும் இன்மையும் ஒடுவயின் ஒக்கும்")])]
    for st, um, steps in choices:
        pre = ""
        if "|" in st:                                          # «எல்லார் | தம்» — இடை வரும் சொல்லோடு உருபு புணரும்
            pre, st = st.split("|")
        stems = [(st, [])]
        if "+இன்" in st:                                      # பெயர் + இன் சாரியை — புணர்ச்சியால்
            w = st.replace("+இன்", "")
            stems = [(s, v) for s, v, _ in _join(w, "இன்")]
        for s, v in stems:
            more = []
            o = to_oli(s)
            if u in ("கு", "அது") and s in KURUMUTHAL:              # எழு. 161, 162 — எனக்கு, எனது; நுமக்கு, நுமது
                a = s[:-1]                                          # ஈறாகு புள்ளி அகரமொடு நிலையும்: என் → என
                st161 = [_p("எழு. 162" if s == "நும்" else "எழு. 161",
                            ("நும் என் இறுதியும் அந்நிலை திரியாது (எழு. 161 போல): " if s == "நும்" else "")
                            + "ஆறன், நான்கன் உருபின் முன் குற்றொற்று இரட்டாது; ஈறாகு புள்ளி அகரமொடு நிலையும்: " + a)]
                if u == "கு":
                    forms = [(a + "க்கு", st161 + [_p("எழு. 114", "வல்லெழுத்து முதலிய உருபுக்கு ஒற்றிடை மிகுதல் வேண்டும்")], N)]
                else:
                    forms = [(a + "து", st161 + [_p("எழு. 115", "ஆறன் உருபின் அகரம் ஈறாகு அகர முன் கெடும்")], N)]
            elif u in ("கு", "கண்") and o[-1] in "அஆஇஈஉஊஎஏஐஒஓஔ" and not _kutriyalukaram(s):
                forms = [(s + "க்" + u, [_p("எழு. 114", "வல்லெழுத்து முதலிய உருபுக்கு ஒற்றிடை மிகுதல் வேண்டும்")], N)]
            else:
                forms = _join(s, u)
            for f, vv, nl in forms:
                f = pre + f
                if um:
                    f = _um(f)
                trace = steps + v + vv + more
                nilai = O if any(t["nilai"] == O for t in trace) or nl == O else N
                res.append(dict(sol=f, vithi=trace, nilai=nilai))
    seen, out = set(), []
    for r in sorted(res, key=lambda r: (_idaiveli(r["sol"]), r["nilai"] != N, len(r["vithi"]))):
        if r["sol"] not in seen:
            seen.add(r["sol"]); out.append(r)
    return out


def _idaiveli(w):
    """உயிர் முன் உயிர் உடம்படுமெய் இன்றி நிற்கும் வடிவு (எழு. 140 «வரையார்») — பின்னே."""
    o = to_oli(w)
    U = "அஆஇஈஉஊஎஏஐஒஓஔ"
    return any(a in U and b in U for a, b in zip(o, o[1:]))


def _um(f):
    """…ஐ + உம் → …ஐயும் (உடம்படுமெய் ய் — ஐ முன்); …உ + உம் → …உம்."""
    r = sorted(punar(f, "உம்", "அல்வழி", thani_vithi=False), key=lambda x: _idaiveli(x["sol"]))
    return r[0]["sol"]
