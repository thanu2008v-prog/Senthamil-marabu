MEY_UNI = {c["uni"][0]: c["cp"] for c in CHART.values() if c["kind"] in ("மெய்", "ஒத்திசைவு — வட எழுத்து")}
UYIR_UNI = {c["uni"]: c["cp"] for c in CHART.values() if c["kind"] == "உயிர்"}
SIGN_UNI = {c["uni"]: c["cp"] for c in CHART.values() if c["kind"] == "உயிர்க்குறி" and c["uni"]}
A_SIGN = BASE + 0x31
OTHER_UNI = {c["uni"]: c["cp"] for c in CHART.values() if c["kind"].startswith("ஒத்திசைவு —") and "வட" not in c["kind"]}
OTHER_UNI["ஃ"] = BASE + 0x0D
BY_CP = {c["cp"]: c for c in CHART.values()}


def to_model(text):
    """யூனிகோடு → மரபு ஒருங்குறி. உயிர்மெய் = மெய் + உயிர்க்குறி; அகர உயிர்மெய்யும் இரு குறி."""
    text = unicodedata.normalize("NFC", text)
    out, i, n = [], 0, len(text)
    while i < n:
        ch = text[i]
        if ch in MEY_UNI:
            nx = text[i + 1] if i + 1 < n else ""
            out.append(chr(MEY_UNI[ch]))
            if nx == PULLI:
                i += 2
            elif nx in SIGN_UNI:
                out.append(chr(SIGN_UNI[nx])); i += 2
            else:
                out.append(chr(A_SIGN)); i += 1
        elif ch in UYIR_UNI:
            out.append(chr(UYIR_UNI[ch])); i += 1
        elif ch in OTHER_UNI:
            out.append(chr(OTHER_UNI[ch])); i += 1
        elif "஀" <= ch <= "௿":
            raise ValueError(f"மாதிரியில் இடம் இல்லாத தமிழ்க் குறி: U+{ord(ch):04X}")
        else:
            out.append(ch); i += 1
    return "".join(out)


def to_unicode(model):
    out, i, n = [], 0, len(model)
    while i < n:
        c = BY_CP.get(ord(model[i]))
        if c is None:
            out.append(model[i]); i += 1; continue
        if c["kind"] in ("மெய்", "ஒத்திசைவு — வட எழுத்து"):
            nx = BY_CP.get(ord(model[i + 1])) if i + 1 < n else None
            if nx and nx["kind"] == "உயிர்க்குறி":
                out.append(c["uni"][0] + nx["uni"]); i += 2
            else:
                out.append(c["uni"]); i += 1
        elif c["kind"] == "உயிர்க்குறி":
            raise ValueError("மெய் இல்லாமல் உயிர்க்குறி (எழு. 18 — உயிர் மெய்யின் வழியதே)")
        else:
            out.append(c["uni"]); i += 1
    return "".join(out)


def valid(model):
    """சேர்க்கை விதி: உயிர்க்குறி மெய்க்குப் பின் மட்டும், ஒன்றே (எழு. 18); உட்புள்ளி மகர மெய்க்குப் பின் மட்டும் (எழு. 14)."""
    prev = None
    for ch in model:
        c = BY_CP.get(ord(ch))
        if c and c["kind"] == "உயிர்க்குறி" and not (prev and prev["kind"] in ("மெய்", "ஒத்திசைவு — வட எழுத்து")):
            return False
        if c and c["kind"] == "உட்புள்ளி" and not (prev and prev["uni"] == "ம்"):
            return False
        prev = c
    return True


def collate_key(text):
    """நூல் வரிசை: உயிர் அ…ஔ, ஆய்தம், மெய் க…ன («அகரமுதல் னகர இறுவாய்», எழு. 1); உயிர்மெய் — மெய், பின் உயிர்."""
    key = []
    for ch in to_model(text):
        c = BY_CP.get(ord(ch))
        if not c:
            key.append((9, ord(ch))); continue
        if c["kind"] == "உயிர்க்குறி":
            key.append((1, UYIR.index(c["name"].split()[-1]) + 1))
        else:
            g = c["uni"][0] if c["uni"] else ""
            key.append((0, COLLATE.index(g) if g in COLLATE else 100 + c["off"]))
    return key
