"""நூல் வழி ஒருங்குறி மாதிரி (மரபு ஒருங்குறி) — தமிழ் எழுத்தின் ஒருங்குறி மாதிரியை இந்நூலின் எழுத்து விதிகளிலிருந்து
புதிதாக அமைத்தல். 128 இடக் கட்டம்; சோதனைக்காகத் தனிப் பயன்பாட்டுப் பகுதியில் (U+EB80–U+EBFF) வைக்கப்படுகிறது —
தற்போதைய தமிழ்க் கட்டம் (U+0B80–U+0BFF) நிலைத்தன்மைக் கொள்கையால் மாற்ற இயலாதது; இது அதற்கு இணையான தனி மாதிரி.

மூலக் கொள்கைகள் (நூற்பாச் சான்று):
 1. அடிப்படை எழுத்து உயிரும் மெய்யும் — «பன்னீ ரெழுத்தும் உயிரென மொழிப» (எழு. 8), «பதினெண் எழுத்தும் மெய்யென
    மொழிப» (எழு. 9). மெய் தனி எழுத்து; அதற்கு உள்ளடங்கிய உயிர் இல்லை — «மெய்யின் இயற்கை புள்ளியொடு நிலையல்»
    (எழு. 15). ஆகவே மெய்க் குறி தனித்து நின்றால் புள்ளியோடு தோன்றும்.
 2. உயிர்மெய் = மெய் + உயிர்க்குறி — «மெய்யின் வழிய துயிர்தோன்று நிலையே» (எழு. 18). பன்னிரண்டு உயிருக்கும்
    உயிர்க்குறி உண்டு, அகரம் உட்பட: அகரக் குறி மெய்யின் உருவை மாற்றாது புள்ளியை மட்டும் நீக்கும்; பிற குறிகள் உருவு
    திரிக்கும் — «உருவுரு வாகி அகரமோ டுயிர்த்தலும் / ஏனை உயிரோ டுருவுதிரிந் துயிர்த்தலும்» (எழு. 17).
 3. ஆய்தம் உயிரும் அல்ல மெய்யும் அல்ல — «முப்பாற் புள்ளி» (எழு. 2); தனி எழுத்து.
 4. மெய்கள் மூவினமாக, நூற்பா வரிசையில் (எழு. 19–21); வல்லினமும் மெல்லினமும் ஒரே பிறப்பிட இணை (எழு. 89–97)
    என்பதால் மெல்லினக் குறி = வல்லினக் குறி + 8 (எழு. 143 இன மெல்லெழுத்து ஒரு கூட்டல்).
 5. உயிர்க்குறி = உயிர் + 0x30 — உயிரும் அதன் குறியும் ஒரே வரிசையில்.
 6. உட்புள்ளி — குறுகிய மகரத்தின் வரிவடிவம்: «உட்பெறு புள்ளி உருவா கும்மே» (எழு. 14). ஒருங்குறியில் இல்லாத, நூல்
    கூறும் வரிவடிவம்.
 7. சார்பெழுத்துகள் (குற்றியலிகரம், குற்றியலுகரம்) தனிக் குறி பெறா — «எழுத்தோ ரன்ன» (எழு. 2); அவை வடிவால் அன்றி
    இடத்தால் அறியப்படுவன (எழு. 34, 36) — பண்பாகக் கணிக்கப்படும்.
 8. நூலில் இல்லாதவை (வட எழுத்து — சொல். 401; எண்ணுரு, குறியீடுகள்) தனி ஒத்திசைவுப் பகுதியில், «நூலில் இல்லை» எனக்
    குறித்து, பழைய உரைகளோடு இழப்பின்றி மாற்ற மட்டும்.
"""
