@lru_cache(None)
def _sollagaram():
    """பெயராக்கி தரும் எல்லா வடிவும் + மாற்று வடிவும் + இணைப்பு வடிவும் → மதிப்பு."""
    L = {}
    for n in list(range(1, 1000)) + [k * 1000 for k in range(1, 100)] + [100000]:
        p = peyar(n)
        if " " not in p["peyar"]:
            L.setdefault(p["peyar"], n)
        for w, _ in p["maatru"]:
            L.setdefault(w, n)
    for w, n in list(L.items()):
        if w.endswith("ூறு"):
            L.setdefault(w[:-2] + "ற்று", n)
        if w.endswith("யிரம்"):
            L.setdefault(w[:-2] + "த்து", n)
        if w.endswith("பஃது"):
            L.setdefault(w[:-4] + "பத்து", n)
        if w.endswith("பது"):
            L.setdefault(w[:-2] + "திற்று", n)
    L.update({"தொண்ணூற்று": 90, "தொன்னாயிரத்து": 900, "ஏழு": 7, "ஒன்பஃது": 9})
    from .punarchi import punar
    for t in range(2, 9):                                     # பத்தூர் கிளவி + அடை வடிவு (பொருள். 644 «முப்பத்திரு»)
        inai = _pathu(t)[0].replace("பஃது", "பத்து")
        for a, v in ADAI.items():
            if v < 10:
                L.setdefault(punar(inai, a, "அல்வழி", thani_vithi=False)[0]["sol"], 10 * t + v)
    return L


def _norm(tok):
    for suf in ("ற்றொடு", "த்தொடு"):
        if tok.endswith(suf):
            return tok[: -len(suf)] + ("று" if suf[0] == "ற" else "து") + "|ஒடு"
    for suf in ("க்", "ச்", "த்", "ப்"):
        if tok.endswith(suf) and len(tok) > 2:
            return tok[:-2]
    return tok


def _atoms(text):
    out = []
    for raw in text.replace("/", " ").split():
        t = _norm(raw)
        L = _sollagaram()
        if t.endswith("|ஒடு"):
            t = t[:-4]
            out.append(("எண்", (L[t], 0), False) if t in L else None)
            out.append(("ஒடு", None)); continue
        if t in ("தலை", "இட்ட", "யிட்ட"):
            out.append(("தலை", None)); continue
        if t == "குறை":
            out.append(("குறை", None)); continue
        if t == THONDU:
            out.append(("எண்", (0, 1), False)); continue
        if t in ADAI:
            out.append(("எண்", (ADAI[t], 0), True)); continue
        if t in L:
            out.append(("எண்", (L[t], 0), False)); continue
        raise ValueError(f"«{raw}» — எண்ணுப்பெயராக அறிய இயலவில்லை")
    # «தலை இட்ட» இரண்டு சொல் ஒன்றாக
    res = []
    for a in out:
        if a[0] == "தலை" and res and res[-1][0] == "தலை":
            continue
        res.append(a)
    return res


def mathippu(text):
    """நூலின் எண் கூற்றை மதிப்பிடுதல். எல்லா வாசிப்புகளும்: {மதிப்பு, …}.
    «தொண்டு» மதிப்பு நூலில் இல்லாததால் விளைவு (மாறிலி, தொண்டின் குணகம்) இணையாகத் தரப்படும் — குணகம் 0 எனில் வெறும் எண்."""
    A = _atoms(text)
    if any(a[0] == "ஒடு" for a in A):                       # «ஒடு» — தொகுதிகளைக் கூட்டும் இணைப்பு; மிகத் தளர்வாகப் பிணைக்கும்
        parts, cur = [], []
        for a in A:
            if a[0] == "ஒடு":
                parts.append(cur); cur = []
            else:
                cur.append(a)
        parts.append(cur)
        vs = [_vals(p) for p in parts if p]
        tot = {(0, 0)}
        for v in vs:
            tot = {(c + c2, k + k2) for c, k in tot for c2, k2 in v}
        return sorted({(c, k) if k else c for c, k in tot}, key=lambda x: x if isinstance(x, int) else x[0])
    return sorted({(c, k) if k else c for c, k in _vals(A)}, key=lambda x: x if isinstance(x, int) else x[0])


def _vals(A):
    A = tuple(A)

    @lru_cache(None)
    def go(i, j):
        """A[i:j] இன் எல்லா மதிப்பும்: {(c, k, adai)}."""
        if j - i == 1:
            a = A[i]
            return {(a[1][0], a[1][1], a[2])} if a[0] == "எண்" else set()
        R = set()
        for m in range(i + 1, j):
            if A[m][0] in ("தலை", "குறை") and m + 1 < j:
                for (c1, k1, _), (c2, k2, _) in _prod(go(i, m), go(m + 1, j)):
                    if A[m][0] == "தலை":
                        R.add((c1 + c2, k1 + k2, False))
                    elif c2 > c1 and not k2:                       # குறை — சிறியது பெரியதிலிருந்து
                        R.add((c2 - c1, -k1, False))
            if A[m][0] in ("தலை", "குறை") or A[m - 1][0] in ("தலை", "குறை"):
                continue
            for (c1, k1, d1), (c2, k2, d2) in _prod(go(i, m), go(m, j)):
                if (d1 or (c1 < 10 and c1 < c2) or (c2 in (100, 1000, 100000) and c1 < c2)) and not k1 and not k2:   # அடுக்கு — பெருக்கல் (பொருள். 644 «ஈர் ஐங்»)
                    R.add((c1 * c2, 0, d2))
                elif not d1 and not d2 and c1 > c2:   # பெரியது முன் — கூட்டல்
                    R.add((c1 + c2, k1 + k2, False))
        return R
    return {(c, k) for c, k, _ in go(0, len(A))}


