"""விளி — நூற்பா கூறும் ஈறும் திரிபும். நூலின் உரையில் விளி எடுத்துக்காட்டு இல்லாததால், சொற்கள் சோதனைக்காக இட்டவை;
ஒவ்வொரு விளைவும் சுட்டப்படும் நூற்பாவின் சொல்லிலிருந்தே பெறப்படுகிறது."""
import pytest
from senthamil_marabu.vili import vili

CASES = [  # (பெயர், திணை, வகை, விளைவு, நூற்பா)
    ("நம்பி", "உயர்திணை", None, "நம்பீ", "சொல். 123"),
    ("நங்கை", "உயர்திணை", None, "நங்காய்", "சொல். 123"),
    ("அன்னை", "உயர்திணை", "முறை", "அன்னா", "சொல். 128"),
    ("ஊரன்", "உயர்திணை", None, "ஊரா", "சொல். 132"),
    ("ஊரன்", "உயர்திணை", None, "ஊர", "சொல். 133"),
    ("சேரமான்", "உயர்திணை", None, "சேரமான்", "சொல். 134"),
    ("வந்தான்", "உயர்திணை", "தொழில்", "வந்தாய்", "சொல். 135"),
    ("மகன்", "உயர்திணை", "முறை", "மகனே", "சொல். 138"),
    ("மன்னர்", "உயர்திணை", None, "மன்னீர்", "சொல். 140"),
    ("வந்தாள்", "உயர்திணை", "தொழில்", "வந்தாய்", "சொல். 148"),
    ("மகள்", "உயர்திணை", "முறை", "மகளே", "சொல். 149"),
    ("வேள்", "உயர்திணை", None, "வேள்", "சொல். 147"),
    ("தோன்றல்", "உயர்திணை", None, "தோன்றால்", "சொல். 146"),
    ("மரம்", "அஃறிணை", None, "மரமே", "சொல். 153"),
    ("கிளி", "அஃறிணை", None, "கிளியே", "சொல். 153"),
]


@pytest.mark.parametrize("peyar,thinai,vagai,want,sutra", CASES)
def test_vili(peyar, thinai, vagai, want, sutra):
    got = [(r["sol"], r["sutra"][0]) for r in vili(peyar, thinai, vagai)]
    assert (want, sutra) in got, got


@pytest.mark.parametrize("peyar", ["தான்", "யான்", "அவன்", "இவள்", "யாவன்", "எவன்", "தமர்", "நுமன்", "மகா", "மரம்"])
def test_vili_kollaathavai(peyar):
    """சொல். 139, 144, 150, 156 — விளி கொள்ளாப் பெயர்; 126 — ஏனை உயிர்; 131 — ஏனைப் புள்ளி."""
    assert vili(peyar) == []
