"""எண்ணுப்பெயர் — நூலின் எண் சொற்களாலும் நூலின் எண்ணிக்கைகளாலும் சோதனை."""
import pytest
from senthamil_marabu import en

# நூலில் வரும் வடிவு → அது குறிக்கும் எண் (நூலின் இடத்தோடு)
VADIVU = [(30, "முப்பஃது", "எழு. 1"), (20, "இருபஃது", "எழு. 103"), (25, "இருபத்தைந்து", "பொருள். 357"), (12, "பன்னிரண்டு", "பொருள். 101"),
          (17, "பதினேழ்", "பொருள். 357"), (15, "பதினைந்து", "சொல். 164"), (18, "பதினெண்", "எழு. 9"), (12, "பன்னீர்", "எழு. 8"),
          (70, "எழுபது", "பொருள். 357"), (50, "ஐம்பது", "பொருள். 464"), (60, "அறுபது", "பொருள். 454"), (500, "ஐஞ்ஞூறு", "பொருள். 406"),
          (625, "அறுநூற்று இருபத்தைந்து", "பொருள். 357"), (1006, "ஆயிரத்து ஆறு", "எழு. 317"), (9, "ஒன்பஃது", "எழு. 82")]


@pytest.mark.parametrize("n,vadivu,idam", VADIVU)
def test_nool_vadivu_peyaril(n, vadivu, idam):
    p = en.peyar(n)
    assert vadivu == p["peyar"] or vadivu in [w for w, _ in p["maatru"]], f"{idam}: {n} → {p['peyar']}"


# நூலின் எண் கூற்று → நூலே (காண்டிகையில் எண்ணிச் சரிபார்த்த) எண்ணிக்கை
KOOTRU = [("எழு. 1", "முப்பஃது", 30), ("எழு. 103", "மூன்று தலை இட்ட முப்பது", 33), ("எழு. 103", "இரண்டு தலை இட்ட இருபஃது", 22),
          ("எழு. 103", "அறு நான்கு", 24), ("எழு. 8", "பன்னீர்", 12), ("எழு. 9", "பதினெண்", 18), ("எழு. 82", "ஒன்பஃது", 9),
          ("பொருள். 101", "பன்னிரண்டு", 12), ("பொருள். 454", "அறுபதிற்று", 60), ("பொருள். 644", "ஈர் ஐங்", 10),
          ("பொருள். 644", "முப்பத்திரு", 32), ("பொருள். 464", "ஐ ஐந்து", 25), ("பொருள். 357", "அறுநூற்று இருபத்தைந்து", 625)]


@pytest.mark.parametrize("idam,kootru,enn", KOOTRU)
def test_nool_kootru_mathippu(idam, kootru, enn):
    assert en.mathippu(kootru) == [enn], idam


def test_suzharchi():
    for n in list(range(1, 2000)) + list(range(2000, 100001, 97)):
        assert n in en.mathippu(en.peyar(n)["peyar"]), n
