@pytest.mark.parametrize("a,b,v,i,want,where", NOOL)
def test_nool_eduthukkaattu(a, b, v, i, want, where):
    got = [r["sol"] for r in punar(a, b, v, i)]
    assert want in got, f"{where}: {a} + {b} → {got}"


def test_oli_round_trip():
    for w in ["கடல்", "மிடற்றுப்பிறந்த", "அஃறிணை", "ஔவை", "தொல்காப்பியம்", "ஞாயிறு"]:
        assert from_oli(to_oli(w)) == w


def test_every_rule_cites_book_and_fires():
    import senthamil_marabu as sm
    ids = {f"{'எழு.'} {r['sutra']}" for r in sm.sutras() if r["padalam"] == "ezhuthu"}
    for r in RULES:
        assert r["sutra"] and all(s in ids for s in r["sutra"]), r["id"]
