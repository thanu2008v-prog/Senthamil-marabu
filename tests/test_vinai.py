@pytest.mark.parametrize("sol,want,idam", NOOL)
def test_nool_sol(sol, want, idam):
    got = [(r["thinai"], r["paal"], r["idam"]) for r in eeru(sol)]
    assert want in got, (idam, got)


def test_eeru_ennikkai():
    """சொல். 204 «ஆயெண்» = 8; 207 «நான்கும்»; 208 «மூன்றும்»; 218 «மூன்றே»; 225, 226 «மூன்றும்»."""
    from senthamil_marabu.vinai import EERU
    c = lambda s: sum(1 for e in EERU if e[5][0] == s)
    assert (c("சொல். 204"), c("சொல். 207"), c("சொல். 208"), c("சொல். 218"), c("சொல். 225"), c("சொல். 226")) == (8, 4, 3, 3, 3, 3)
