@pytest.mark.parametrize("enn,vadivu,idam", [("ஆறு", "ஆறன்", "எழு. 115"), ("நான்கு", "நான்கன்", "எழு. 123"), ("எட்டு", "எட்டன்", "எழு. 450")])
def test_ennin_saariyai(enn, vadivu, idam):
    assert vadivu in [s for s, _, _ in saariyai(enn)], idam


def test_palavai_vatru():
    assert [s for s, _, _ in saariyai("பல", palavai=True)] == ["பலவற்று"]       # எழு. 210 «பலவற் றிறுதி»


def test_kurumuthal_naankan_aaran():
    """எழு. 161, 162 — நெடுமுதல் குறுகும் மொழி + நான்கன் / ஆறன் உருபு: ஒற்று இரட்டாது, அகரமொடு நிலையும்."""
    from senthamil_marabu.urupu import urupu
    want = {("யான்", "கு"): "எனக்கு", ("யான்", "அது"): "எனது", ("யாம்", "கு"): "எமக்கு", ("நாம்", "கு"): "நமக்கு", ("தான்", "கு"): "தனக்கு",
            ("தாம்", "அது"): "தமது", ("நீ", "கு"): "நினக்கு", ("நீ", "அது"): "நினது", ("நும்", "கு"): "நுமக்கு", ("நும்", "அது"): "நுமது"}
    for (p, u), w in want.items():
        r = urupu(p, u)
        assert r[0]["sol"] == w, (p, u, r[0]["sol"])
        assert any(v["sutra"] in ("எழு. 161", "எழு. 162") for v in r[0]["vithi"])
    assert urupu("யான்", "ஐ")[0]["sol"] == "என்னை"                 # பிற உருபில் இரட்டும் (எழு. 160)


NOOL_161 = [("தாம்", "தமக்கு", "சொல். 4 «அந்தம் தமக்கு இலவே»"), ("தான்", "தனக்கு", "பொருள். 118 «அறம் தனக்கு இன்மையின்»"),
            ("யாம்", "எமக்கு", "பொருள். 144 «புரையுமால் எமக்கு என»")]


@pytest.mark.parametrize("peyar,vadivu,idam", NOOL_161)
def test_nool_vadivu_161(peyar, vadivu, idam):
    """நூலிலேயே வரும் நான்கன் உருபு வடிவம் — எழு. 161-இன் விளைவு நூலின் சொந்தச் சொல்லோடு ஒக்க வேண்டும்."""
    from senthamil_marabu.urupu import urupu
    import senthamil_marabu as sm
    assert urupu(peyar, "கு")[0]["sol"] == vadivu, idam
    assert any(vadivu in r["moolam"] for r in sm.sutras()), idam
