def cell(c):
    if not c:
        return ""
    if c["kind"] == "உயிர்க்குறி":
        return "◌" + c["uni"] if c["uni"] else "◌அ"
    if c["kind"] == "உட்புள்ளி":
        return "◌·"
    return c["uni"]


